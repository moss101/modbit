// Generates packages/ui/src/icons.generated.ts: Lucide's path data (ISC, lucide-react 1.17.0) for the icons the renderer draws.
// usage: node tools/zcode-reference/scripts/gen-icons.mjs <path to node_modules/lucide-react of the harness work directory>
// Only the shape data is copied (tag and attributes, never a React component); no icon package becomes a dependency of Modbit.
// Licences: third-party/zcode-ui/LUCIDE-LICENSE. Add a name here and rerun to extend the table.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

export const ICONS = ["plus", "settings", "trash-2", "chevron-down", "chevron-right", "check", "x", "search", "panel-left", "panel-right", "chevron-left", "ellipsis", "monitor", "pin", "archive", "funnel", "folder-plus", "pencil", "rotate-ccw", "bookmark"];

const dir = process.argv[2];
if (!dir) throw new Error("usage: gen-icons.mjs <lucide-react dir>");
const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
const OUT = fileURLToPath(new URL("../../../packages/ui/src/icons.generated.ts", import.meta.url));

const entries = [];
for (const name of ICONS) {
  // The icon modules import React; read the node list from the source text instead of executing them.
  const src = readFileSync(join(dir, "dist", "esm", "icons", `${name}.mjs`), "utf8");
  const m = /const __iconNode = (\[[\s\S]*?\]);\n/.exec(src);
  if (!m) throw new Error(`no icon node in ${name}`);
  const nodes = Function(`return ${m[1]}`)().map(([tag, attrs]) => [tag, Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== "key"))]);
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`);
}
writeFileSync(OUT, `/**
 * Lucide icon shapes (https://lucide.dev, lucide-react ${pkg.version}), the icon family ZCode draws with (DR-PX-2026-10-24-016, ZDL-07).
 *
 * GENERATED by tools/zcode-reference/scripts/gen-icons.mjs. Do not edit. Only the path data is copied, as typed data.
 * Licence: ISC, and MIT for the icons derived from Feather: third-party/zcode-ui/LUCIDE-LICENSE (Copyright (c) 2026 Lucide Icons
 * and Contributors; Copyright (c) 2013-present Cole Bemis). Every viewBox is 24 x 24, stroke 2, round caps and joins.
 */
export type IconNode = readonly (readonly [tag: string, attrs: Readonly<Record<string, string>>])[];

export const ICON_NODES = {
${entries.join("\n")}
} as const satisfies Record<string, IconNode>;

export type IconName = keyof typeof ICON_NODES;
`);
console.log(ICONS.length, "icons ->", OUT);
