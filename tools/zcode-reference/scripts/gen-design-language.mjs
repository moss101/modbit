// Generates packages/design-tokens/src/design-language.ts from the retained reference capture (evidence/zcode-ui/reference).
// Run from anywhere: node tools/zcode-reference/scripts/gen-design-language.mjs
// A token is kept as ZCode declared it when that is a plain #hex or rgb()/rgba() literal; an oklch() or color-mix() value is
// kept as the canonical sRGB literal the browser resolved it to. The Tailwind palette scales and the ZCode feature families
// Modbit does not have (EXCLUDE) are not part of the table.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const REF = fileURLToPath(new URL("../../../evidence/zcode-ui/reference/", import.meta.url));
const OUT = fileURLToPath(new URL("../../../packages/design-tokens/src/design-language.ts", import.meta.url));
const resolved = JSON.parse(readFileSync(REF + "zcode-tokens-resolved.json", "utf8"));
const rgba = JSON.parse(readFileSync(REF + "zcode-colors-rgba.json", "utf8"));

const PALETTE = /^(neutral|sky|green|violet|red|yellow|blue|amber|cyan|slate|teal|fuchsia|indigo|rose|black|white)(-|$)/;
const FOREIGN = /^(trajectory|workflow|usage|plugin|subagent|session|feedback|icon|remote|animated)(-|$)/;
const KEEP_REMOTE = new Set(["remote-foreground-muted", "remote-docker-foreground"]);

const names = Object.keys(rgba.light).map((k) => k.slice("--color-".length)).filter((n) => (KEEP_REMOTE.has(n) || !FOREIGN.test(n)) && !PALETTE.test(n)).sort();

const hex = (v) => "#" + v.map((x) => x.toString(16).padStart(2, "0")).join("");
function literal(theme, name) {
  const declared = (resolved[theme][`--color-${name}`] ?? "").trim();
  if (/^#[0-9a-fA-F]{6}$/.test(declared)) return declared.toLowerCase();
  if (/^rgba?\(/.test(declared)) return declared.replace(/\s+/g, " ");
  const [r, g, b, a] = rgba[theme][`--color-${name}`];
  return a >= 1 ? hex([r, g, b]) : `rgba(${r}, ${g}, ${b}, ${a})`;
}
const table = (theme) => names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(literal(theme, n))},`).join("\n");

writeFileSync(OUT, `/**
 * ZCode's colour tokens for its two active themes, Zai Light (Modbit "light") and Zai Dark (Modbit "dark"), as canonical sRGB
 * literals (DR-PX-2026-10-24-016, ZDL-01).
 *
 * GENERATED by tools/zcode-reference/scripts/gen-design-language.mjs from evidence/zcode-ui/reference (ZCode revision
 * 3c5b227649371507ddc4eb46ac5133afe6db1cab). Do not edit: change the capture or the generator.
 *
 * Origin and licence: token names and values are taken from ZCode (https://github.com/zai-org/ZCode, packages/ui/src/styles.css,
 * Apache-2.0); values that ZCode derives from the Tailwind CSS palette (MIT) are the colours that palette resolves to. This file
 * is a modified, machine-resolved extract (oklch() and color-mix() values are stored as the sRGB they resolve to) and is not
 * ZCode's source file. See third-party/zcode-ui/NOTICE.md. No ZCode name, logo or mark is part of it.
 */

export const ZDL_TOKENS = [
${names.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
] as const;
export type ZdlToken = (typeof ZDL_TOKENS)[number];
export type ZdlColors = Record<ZdlToken, string>;

export const ZDL_LIGHT: ZdlColors = {
${table("light")}
};

export const ZDL_DARK: ZdlColors = {
${table("dark")}
};
`);
console.log(names.length, "tokens ->", OUT);
