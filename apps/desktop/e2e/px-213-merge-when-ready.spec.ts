const SHOTS = process.env.MODBIT_SHOTS_DIR ?? "";
const TOKEN = "ghp_e2e_token_0213";

interface Fake {
  server: Server;
  url: string;
  requests: { method: string; path: string; authorized: boolean }[];
  pull: { number: number; head: string; state: "open" | "closed"; merged: boolean } | null;
  /** The merges the forge was asked for (PUT /pulls/1/merge bodies). */
  merges: { sha?: string; merge_method?: string }[];
  /** The head the forge reports; a new value is a new push someone made. */
  sha: string;
  runs: { id: number; name: string; status: string; conclusion: string | null }[];
}

/** A GitHub REST fake in the documented shapes: create and list pull requests, read one with its reviews, its check runs. */
function fakeGithub(): Promise<Fake> {
  const fake = { requests: [], pull: null, runs: [], merges: [], sha: "f".repeat(40) } as unknown as Fake;
  return new Promise((done) => {
    fake.server = createServer((req, res) => {
      let body = "";
      req.on("data", (c) => (body += c));
      req.on("end", () => {
        const authorized = req.headers.authorization === `Bearer ${TOKEN}`;
        const url = req.url ?? "";
        fake.requests.push({ method: req.method ?? "", path: url, authorized });
        const reply = (status: number, payload: unknown) => {
          res.writeHead(status, { "content-type": "application/json" });
          res.end(JSON.stringify(payload));
        };
        if (!authorized) return reply(401, { message: "Bad credentials" });
        const [path = ""] = url.split("?");
        const view = () => {
          const p = fake.pull!;
          return {
            number: p.number,
            url: `${fake.url}/repos/o/r/pulls/${p.number}`,
            html_url: `https://github.test/o/r/pull/${p.number}`,
            state: p.state,
            merged: p.merged,
            draft: false,
            mergeable: true,
            mergeable_state: "clean",
            title: "annotate line 2",
            body: "Generated by Modbit",
            user: { login: "modbit-bot" },
            head: { ref: p.head, sha: fake.sha },
            base: { ref: "main" },
            labels: [],
            requested_reviewers: [],
            commits: 1,
            additions: 1,
            deletions: 1,
            changed_files: 1,
            comments: 0,
            review_comments: 0,
            created_at: "2026-11-22T10:00:00Z",
            updated_at: "2026-11-22T10:00:00Z",
            merge_commit_sha: fake.pull?.merged ? "e".repeat(40) : null,
          };
        };
        if (path === "/repos/o/r/pulls" && req.method === "POST") {
          const head = (JSON.parse(body || "{}") as { head?: string }).head ?? "";
          if (fake.pull) return reply(422, { message: "Validation Failed", errors: [{ resource: "PullRequest", code: "custom", message: `A pull request already exists for o:${head}.` }] });
          fake.pull = { number: 1, head, state: "open", merged: false };
          return reply(201, view());
        }
        if (path === "/repos/o/r/pulls" && req.method === "GET") return reply(200, fake.pull ? [view()] : []);
        if (path === "/repos/o/r/pulls/1" && req.method === "GET") return fake.pull ? reply(200, view()) : reply(404, { message: "Not Found" });
        if (path === "/repos/o/r/pulls/1/reviews" && req.method === "GET") return reply(200, []);
        // Merge as GitHub documents it: 409 when `sha` is not the head, 405 when it cannot be merged, 200 with the merge commit.
        if (path === "/repos/o/r/pulls/1/merge" && req.method === "PUT") {
          const b = JSON.parse(body || "{}") as { sha?: string; merge_method?: string };
          fake.merges.push(b);
          const p = fake.pull;
          if (!p) return reply(404, { message: "Not Found" });
          if (b.sha && b.sha !== fake.sha) return reply(409, { message: "Head branch was modified. Review and try the merge again." });
          if (p.state !== "open" || p.merged) return reply(405, { message: "Pull Request is not mergeable" });
          p.state = "closed";
          p.merged = true;
          return reply(200, { sha: "e".repeat(40), merged: true, message: "Pull Request successfully merged" });
        }
        if ((path === "/repos/o/r/pulls/1/comments" || path === "/repos/o/r/issues/1/comments") && req.method === "GET") return reply(200, []);
        // The runs are the head's; the Core's CI evidence asks about the commit it pushed, and is answered with the same runs.
        const runsOf = /^\/repos\/o\/r\/commits\/([0-9a-f]{40})\/check-runs$/.exec(path);
        if (runsOf && req.method === "GET") {
          const sha = runsOf[1]!;
          return reply(200, { total_count: fake.runs.length, check_runs: fake.runs.map((r) => ({ ...r, head_sha: sha, html_url: `https://github.test/o/r/runs/${r.id}`, completed_at: r.status === "completed" ? "2026-11-21T10:05:00Z" : null, output: { title: r.name, summary: "", text: "" } })) });
        }
        return reply(404, { message: "Not Found" });
      });
    });
    fake.server.listen(0, "127.0.0.1", () => {
      fake.url = `http://127.0.0.1:${(fake.server.address() as { port: number }).port}`;
      done(fake);
    });
  });
}

async function shots(page: Page, name: string): Promise<void> {
  if (!SHOTS) return;
  mkdirSync(SHOTS, { recursive: true });
  for (const theme of ["light", "dark"] as const) {
    await page.evaluate((t) => document.documentElement.setAttribute("data-theme", t), theme);
    await page.waitForTimeout(250);
    await page.screenshot({ path: join(SHOTS, `${name}-${theme}.png`) });
  }
  await page.evaluate(() => document.documentElement.setAttribute("data-theme", "light"));
}

/** The task's header as the Core serves it (archived ones included). */
async function headerOf(page: Page, sessionId: string, taskId: string) {
  const v = await page.evaluate((s) => window.modbit.agentHeaders(s, true), sessionId);
  return v.headers.find((h) => h.taskId === taskId)!;
}


test("PX-213: merge when ready waits for the checks, asks on the approval card once they pass, asks again when the head moves, and merges only the approved head", async () => {
  test.setTimeout(300_000);
  const repo = mkdtempSync(join(tmpdir(), "modbit-px213-repo-"));
  const bare = mkdtempSync(join(tmpdir(), "modbit-px213-bare-"));
  makeRepo(repo);
  git(repo, "config", "core.autocrlf", "false");
  execFileSync("git", ["init", "-q", "--bare", "-b", "main", bare]);
  git(repo, "remote", "add", "origin", "https://github.test/o/r.git");
  git(repo, "config", `url.${bare}.insteadOf`, "https://github.test/o/r.git");
  const gh = await fakeGithub();
  const model = await routedModel((_goal, results) => {
    const script: ModelPart[][] = [
      [{ call: { name: "fs.read", args: { path: "notes.txt" } } }],
      [{ call: { name: "plan.update", args: { outcome: "annotate", expected_files: ["notes.txt"] } } }],
      [{ call: { name: "change.apply", args: { path: "notes.txt", op: "replace", content: "line 1\nline 2 annotated\nline 3\n" } } }],
      [{ call: { name: "task.complete", args: { summary: "annotated", self_review: { findings: [] } } } }],
    ];
    return script[results] ?? ["Nothing further."];
  });
  const dataDir = mkdtempSync(join(tmpdir(), "modbit-e2e-px213-"));
  const env = { MODBIT_OPENAI_BASE_URL: model.url, MODBIT_GITHUB_API_BASE_URL: gh.url, MODBIT_GITHUB_TOKEN: TOKEN, MODBIT_GITHUB_WEB_HOST: "github.test", MODBIT_PR_REFRESH_SECS: "0" };
  const { app, page } = await launch(dataDir, { env });
  try {
    await setContentSize(app, page, 1440, 900);
    const taskId = await runTask(page, "annotate line 2", repo);
    const sessionId = await sessionOf(page);
    await expectTaskState(page, taskId, "ReadyForReview", 90_000);
    await expect(page.getByTestId("review")).toBeVisible({ timeout: 15_000 });
    await page.getByTestId("review-close").click();
    await openTask(page, taskId);
    await showPane(page, "pull-request");
    const pane = page.getByTestId("pane-pull-request");
    const app_ = pane.getByTestId("app-pull-request");
    await expect(app_).toHaveAttribute("data-task-state", "ReadyForReview", { timeout: 30_000 });

    // ---- Opened through its approval on the docked card.
    await pane.getByTestId("pr-pane-open").click();
    await expect(app_).toHaveAttribute("data-status", "APPROVAL_PENDING", { timeout: 30_000 });
    const card = page.getByTestId("approval-card");
    await expect(card).toBeVisible({ timeout: 30_000 });
    await card.getByTestId("approval-run").click();
    await expect(card.getByTestId("approval-confirm")).toBeVisible();
    await card.getByTestId("approval-confirm-run").click();
    await expect(app_).toHaveAttribute("data-status", "OPENED", { timeout: 60_000 });
    await expect(card).toBeHidden({ timeout: 30_000 });

    // ---- Off by default; a check is still running.
    gh.runs = [{ id: 601, name: "build", status: "in_progress", conclusion: null }];
    const refresh = () => page.getByTestId("pane-head-pull-request").getByTestId("pr-pane-refresh").click();
    await refresh();
    await expect(pane.getByTestId("pr-pane-state")).toHaveAttribute("data-checks", "PENDING", { timeout: 30_000 });
    const merge = pane.getByTestId("pr-pane-merge");
    const toggle = pane.getByTestId("pr-pane-merge-switch");
    await expect(merge).toHaveAttribute("data-phase", "OFF");
    await expect(toggle).not.toBeChecked();
    await expect(pane.getByTestId("pr-pane-merge-detail")).toHaveText("Off. When on, Modbit asks you to approve the merge once the checks pass; nothing merges without your approval.");

    // ---- Asked for, squash: it waits for the running check, and nothing asks.
    await pane.getByTestId("pr-pane-merge-method").selectOption("squash");
    await toggle.click();
    await expect(toggle).toBeChecked({ timeout: 15_000 });
    await expect(merge).toHaveAttribute("data-phase", "WAITING");
    await expect(pane.getByTestId("pr-pane-merge-detail")).toHaveText("Waiting for 1 check(s) to finish. Method: squash.");
    await expect(pane.getByTestId("pr-pane-merge-method")).toBeDisabled();
    await page.waitForTimeout(1_500);
    await expect(card).toBeHidden();
    await accessible(page, "the Pull request pane with merge when ready waiting", '[data-testid="pane-pull-request"]');
    await shots(page, "merge-waiting");

    // ---- The checks pass: the approval card asks for the merge of that head. Nothing is merged yet.
    const h1 = gh.sha;
    gh.runs = [{ id: 601, name: "build", status: "completed", conclusion: "success" }];
    await refresh();
    await expect(merge).toHaveAttribute("data-phase", "ASKED", { timeout: 30_000 });
    await expect(card).toBeVisible({ timeout: 30_000 });
    await expect(card).toContainText("forge.pr.merge");
    const hex = (id: string) => id.replace(/-/g, "");
    await expect(pane.getByTestId("pr-pane-merge-detail")).toContainText(`Checks passed at ${h1.slice(0, 12)}`);
    const first = (await headerOf(page, sessionId, taskId)).pullRequest!;
    expect([first.mergeHeadSha, first.mergeMethod]).toEqual([h1, "squash"]);
    await expect(card).toHaveAttribute("data-approval-id", hex(first.mergeApprovalId), { timeout: 15_000 });
    expect(gh.merges).toEqual([]);
    await accessible(page, "the merge asking on the approval card", '[data-testid="approval-card"]');
    await shots(page, "merge-asked");

    // ---- Someone pushes before the decision: that ask is void, and the card asks again for the new head.
    gh.sha = "1".repeat(40);
    await refresh();
    await expect.poll(async () => (await headerOf(page, sessionId, taskId)).pullRequest?.mergeHeadSha, { timeout: 30_000 }).toBe(gh.sha);
    const second = (await headerOf(page, sessionId, taskId)).pullRequest!;
    expect(second.mergeApprovalId).not.toBe(first.mergeApprovalId);
    await expect(pane.getByTestId("pr-pane-merge-detail")).toContainText(`Checks passed at ${gh.sha.slice(0, 12)}`, { timeout: 15_000 });
    // The card now asks about the new head's approval (the void reached it).
    await expect(card).toHaveAttribute("data-approval-id", hex(second.mergeApprovalId), { timeout: 30_000 });
    // The first ask is named as withdrawn, never as one the person let expire.
    await expect(page.getByTestId("approval-expired").first()).toHaveAttribute("data-state", "WITHDRAWN", { timeout: 15_000 });
    await expect(page.getByTestId("conv-approval-withdrawn").first()).toBeVisible({ timeout: 15_000 });
    await shots(page, "merge-head-moved");
    expect(gh.merges).toEqual([]);

    // ---- Allowed on the card: the forge is asked to merge exactly that head, squashed, once; the pane says it merged.
    await card.getByTestId("approval-run").click();
    if (await card.getByTestId("approval-confirm").isVisible()) await card.getByTestId("approval-confirm-run").click();
    await expect(merge).toHaveAttribute("data-phase", "MERGED", { timeout: 60_000 });
    await expect(pane.getByTestId("pr-pane-merge-detail")).toHaveText(`Merged ${gh.sha.slice(0, 12)} as eeeeeeeeeeee.`);
    await expect(pane.getByTestId("pr-pane-state")).toHaveAttribute("data-state", "MERGED", { timeout: 30_000 });
    expect(gh.merges).toEqual([{ sha: "1".repeat(40), merge_method: "squash" }]);
    await accessible(page, "the merged request", '[data-testid="pane-pull-request"]');
    await shots(page, "merge-merged");
  } finally {
    await closeApp(app);
    model.server.close();
    gh.server.close();
  }
});
