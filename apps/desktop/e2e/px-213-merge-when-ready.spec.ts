/**
 * PX-213 (QUAL-PX-213 / PX-E2E-213, DR-PX-2026-11-11-021 MWS-17): merge when ready. The real Electron app and the real
 * modbit-core, a scripted model, a real git repository pushing to a real bare remote, and a GitHub REST fake in this process in
 * GitHub's documented shapes. The renderer merges nothing: the request is the Core's, the Core raises the merge's approval, and the
 * merge happens only on the person's decision on the docked approval card.
 *
 * Proven here: the Pull request pane's Merge when ready switch is off by default; asked for with a method while a check runs, it
 * waits and says for what, and nothing asks; once the checks pass the approval card asks for `forge.pr.merge`; a push that moves
 * the head before the decision voids that ask and the card asks again for the new head; allowed there, the forge is asked to merge
 * exactly that head with that method, once, and the pane says it merged.
 *
 * Not proven here: the same against real GitHub, or in a packaged app; denial, the tool's refusals and restart (the Core
 * qualification proves them).
 */
