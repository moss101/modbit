/**
 * PX-211 (QUAL-PX-211 / PX-E2E-211, DR-PX-2026-11-11-021 MWS-17): a task's pull request after it was opened. The real Electron
 * app and the real modbit-core, a scripted model, a real git repository pushing to a real bare remote, and a GitHub REST fake in
 * this process that answers in GitHub's documented shapes. The renderer makes no forge call: Refresh asks the Core to read, and
 * the Core's schedule reads on its own.
 *
 * Proven here: the request opened through its approval is named by the task's header with no state until the Core reads it;
 * Refresh reads checks failing, then checks passing, each equal to the server's, and the row, the preview card, the details rail
 * and the Pull request pane all show what was read and when; after the app and its Core restart the header is the same; with
 * archive after merge turned on in Settings, the Core's schedule reads the merge, archives the task and the list offers Undo,
 * which brings it back for good.
 *
 * Not proven here: the same against real GitHub (the forge adapter's read path is, by PX-125's live leg), or in a packaged app.
 */
