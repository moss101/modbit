const SHOTS = process.env.MODBIT_SHOTS_DIR ?? "";
const TOKEN = "ghp_e2e_token_0211";
const HEAD = "f".repeat(40);

interface Fake {
  server: Server;
  url: string;
  requests: { method: string; path: string; authorized: boolean }[];
  pull: { number: number; head: string; state: "open" | "closed"; merged: boolean } | null;
  runs: { id: number; name: string; status: string; conclusion: string | null }[];
}

/** A GitHub REST fake in the documented shapes: create and list pull requests, read one with its reviews, its check runs. */
function fakeGithub(): Promise<Fake> {
  const fake = { requests: [], pull: null, runs: [] } as unknown as Fake;
  return new Promise((done) => {
    fake.server = createServer((req, res) => {
      let body = "";
      req.on("data", (c) => (body += c));
      req.on("end", () => {
        const authorized = req.headers.authorization === `Bearer ${TOKEN}`;
        const url = req.url ?? "";
        fake.requests.push({ method: req.method ?? "", path: url, authorized });
        const reply = (status: number, payload: unknown) => {
          res.writeHead(status, { "content-type": "application/json" });
          res.end(JSON.stringify(payload));
        };
        if (!authorized) return reply(401, { message: "Bad credentials" });
        const [path = ""] = url.split("?");
        const view = () => {
          const p = fake.pull!;
          return {
            number: p.number,
            url: `${fake.url}/repos/o/r/pulls/${p.number}`,
            html_url: `https://github.test/o/r/pull/${p.number}`,
            state: p.state,
            merged: p.merged,
            draft: false,
            mergeable: true,
            mergeable_state: "clean",
            title: "annotate line 2",
            body: "Generated by Modbit",
            user: { login: "modbit-bot" },
            head: { ref: p.head, sha: HEAD },
            base: { ref: "main" },
            labels: [],
            requested_reviewers: [],
            commits: 1,
            additions: 1,
            deletions: 1,
            changed_files: 1,
            comments: 0,
            review_comments: 0,
            created_at: "2026-11-21T10:00:00Z",
            updated_at: "2026-11-21T10:00:00Z",
          };
        };
        if (path === "/repos/o/r/pulls" && req.method === "POST") {
          const head = (JSON.parse(body || "{}") as { head?: string }).head ?? "";
          if (fake.pull) return reply(422, { message: "Validation Failed", errors: [{ resource: "PullRequest", code: "custom", message: `A pull request already exists for o:${head}.` }] });
          fake.pull = { number: 1, head, state: "open", merged: false };
          return reply(201, view());
        }
        if (path === "/repos/o/r/pulls" && req.method === "GET") return reply(200, fake.pull ? [view()] : []);
        if (path === "/repos/o/r/pulls/1" && req.method === "GET") return fake.pull ? reply(200, view()) : reply(404, { message: "Not Found" });
        if (path === "/repos/o/r/pulls/1/reviews" && req.method === "GET") return reply(200, []);
        if ((path === "/repos/o/r/pulls/1/comments" || path === "/repos/o/r/issues/1/comments") && req.method === "GET") return reply(200, []);
        // The runs are the head's; the Core's CI evidence asks about the commit it pushed, and is answered with the same runs.
        const runsOf = /^\/repos\/o\/r\/commits\/([0-9a-f]{40})\/check-runs$/.exec(path);
        if (runsOf && req.method === "GET") {
          const sha = runsOf[1]!;
          return reply(200, { total_count: fake.runs.length, check_runs: fake.runs.map((r) => ({ ...r, head_sha: sha, html_url: `https://github.test/o/r/runs/${r.id}`, completed_at: r.status === "completed" ? "2026-11-21T10:05:00Z" : null, output: { title: r.name, summary: "", text: "" } })) });
        }
        return reply(404, { message: "Not Found" });
      });
    });
    fake.server.listen(0, "127.0.0.1", () => {
      fake.url = `http://127.0.0.1:${(fake.server.address() as { port: number }).port}`;
      done(fake);
    });
  });
}

async function shots(page: Page, name: string): Promise<void> {
  if (!SHOTS) return;
  mkdirSync(SHOTS, { recursive: true });
  for (const theme of ["light", "dark"] as const) {
    await page.evaluate((t) => document.documentElement.setAttribute("data-theme", t), theme);
    await page.waitForTimeout(250);
    await page.screenshot({ path: join(SHOTS, `${name}-${theme}.png`) });
  }
  await page.evaluate(() => document.documentElement.setAttribute("data-theme", "light"));
}

/** The task's header as the Core serves it (archived ones included). */
async function headerOf(page: Page, sessionId: string, taskId: string) {
  const v = await page.evaluate((s) => window.modbit.agentHeaders(s, true), sessionId);
  return v.headers.find((h) => h.taskId === taskId)!;
}

/** Opens a row's preview card from the keyboard (home is open) and returns it, re-opening it if focus moved under it. */
async function previewOf(page: Page, taskId: string) {
  await toNewTask(page);
  const card = page.getByTestId("agent-preview");
  await expect(async () => {
    if (!(await card.isVisible())) {
      await agentRow(page, taskId).getByTestId("agent-open").focus();
      await page.keyboard.press("Space");
    }
    await expect(card).toHaveAttribute("data-task-id", taskId, { timeout: 2_000 });
    await page.waitForTimeout(700);
    await expect(card).toHaveAttribute("data-task-id", taskId, { timeout: 1_000 });
  }).toPass({ timeout: 30_000 });
  return card;
}

test("PX-211: the Core reads a task's pull request through the forge adapter, the header, row, card, rail and pane show what it read and when, a restart keeps it, and archive after merge is a preference with Undo", async () => {
  test.setTimeout(360_000);
  const repo = mkdtempSync(join(tmpdir(), "modbit-px211-repo-"));
  const bare = mkdtempSync(join(tmpdir(), "modbit-px211-bare-"));
  makeRepo(repo);
  git(repo, "config", "core.autocrlf", "false");
  execFileSync("git", ["init", "-q", "--bare", "-b", "main", bare]);
  git(repo, "remote", "add", "origin", "https://github.test/o/r.git");
  git(repo, "config", `url.${bare}.insteadOf`, "https://github.test/o/r.git");
  const gh = await fakeGithub();
  const model = await routedModel((_goal, results) => {
    const script: ModelPart[][] = [
      [{ call: { name: "fs.read", args: { path: "notes.txt" } } }],
      [{ call: { name: "plan.update", args: { outcome: "annotate", expected_files: ["notes.txt"] } } }],
      [{ call: { name: "change.apply", args: { path: "notes.txt", op: "replace", content: "line 1\nline 2 annotated\nline 3\n" } } }],
      [{ call: { name: "task.complete", args: { summary: "annotated", self_review: { findings: [] } } } }],
    ];
    return script[results] ?? ["Nothing further."];
  });
  const dataDir = mkdtempSync(join(tmpdir(), "modbit-e2e-px211-"));
  writeFileSync(join(dataDir, "admin-config.json"), JSON.stringify({ review_comment_authors: ["reviewer"] }));
  const env = { MODBIT_OPENAI_BASE_URL: model.url, MODBIT_GITHUB_API_BASE_URL: gh.url, MODBIT_GITHUB_TOKEN: TOKEN, MODBIT_GITHUB_WEB_HOST: "github.test" };
  // The first run reads only when asked; the second lets the Core's schedule read every two seconds.
  let { app, page } = await launch(dataDir, { env: { ...env, MODBIT_PR_REFRESH_SECS: "0" } });
  try {
    await setContentSize(app, page, 1440, 900);
    const taskId = await runTask(page, "annotate line 2", repo);
    const sessionId = await sessionOf(page);
    await expectTaskState(page, taskId, "ReadyForReview", 90_000);
    await expect(page.getByTestId("review")).toBeVisible({ timeout: 15_000 });
    await page.getByTestId("review-close").click();
    await openTask(page, taskId);
    await showPane(page, "pull-request");
    const pane = page.getByTestId("pane-pull-request");
    const app_ = pane.getByTestId("app-pull-request");
    await expect(app_).toHaveAttribute("data-task-state", "ReadyForReview", { timeout: 30_000 });
    await expect(pane.getByTestId("pr-pane-state"), "no request, no state").toHaveCount(0);
    expect((await headerOf(page, sessionId, taskId)).pullRequest).toBeUndefined();

    // ---- Opened through its approval (the docked approval card is the one place it is decided).
    await pane.getByTestId("pr-pane-open").click();
    await expect(app_).toHaveAttribute("data-status", "APPROVAL_PENDING", { timeout: 30_000 });
    const card = page.getByTestId("approval-card");
    await expect(card).toBeVisible({ timeout: 30_000 });
    await card.getByTestId("approval-run").click();
    await expect(card.getByTestId("approval-confirm")).toBeVisible();
    await card.getByTestId("approval-confirm-run").click();
    await expect(app_).toHaveAttribute("data-status", "OPENED", { timeout: 60_000 });
    expect(gh.pull?.number).toBe(1);

    // The header names the request with no state: nothing has been read.
    const state = pane.getByTestId("pr-pane-state");
    await expect(state).toHaveAttribute("data-number", "1", { timeout: 30_000 });
    await expect(state).toHaveAttribute("data-state", "UNREAD");
    await expect(pane.getByTestId("pr-pane-state-word")).toHaveText("not read yet");
    await expect(pane.getByTestId("pr-pane-read-at")).toContainText("has not read this request");
    const row = agentRow(page, taskId);
    await expect(row.getByTestId("agent-pr")).toHaveAttribute("data-state", "UNREAD");
    let h = await headerOf(page, sessionId, taskId);
    expect([h.pullRequest?.number, h.pullRequest?.state, h.pullRequest?.readAtMs]).toEqual([1, "", 0]);
    expect(gh.requests.some((r) => r.method === "GET" && r.path.startsWith("/repos/o/r/pulls/1")), "opening is not a read").toBe(false);

    // ---- Checks failing on the server; Refresh reads them.
    gh.runs = [
      { id: 501, name: "build", status: "completed", conclusion: "success" },
      { id: 502, name: "lint", status: "completed", conclusion: "failure" },
    ];
    await page.getByTestId("pane-head-pull-request").getByTestId("pr-pane-refresh").click();
    await expect(state).toHaveAttribute("data-state", "OPEN", { timeout: 30_000 });
    await expect(state).toHaveAttribute("data-checks", "FAILING");
    await expect(pane.getByTestId("pr-pane-state-word")).toHaveText("open");
    await expect(pane.getByTestId("pr-pane-state-checks")).toHaveText("Checks: 1 of 2 checks failing (lint)");
    await expect(pane.getByTestId("pr-pane-read-at")).toContainText("Read just now, when asked.");
    await expect(row.getByTestId("agent-pr")).toHaveAttribute("data-checks", "FAILING", { timeout: 15_000 });
    h = await headerOf(page, sessionId, taskId);
    expect([h.pullRequest?.state, h.pullRequest?.checks, h.pullRequest?.failingChecks, h.pullRequest?.trigger]).toEqual(["OPEN", "FAILING", ["lint"], "REQUEST"]);
    expect(h.pullRequest!.readAtMs).toBeGreaterThan(0);
    // The details rail carries the same read (beside the conversation, or under More while the dock takes the width).
    await openTaskDetails(page);
    await expect(page.getByTestId("rail-pull-request-state")).toHaveAttribute("data-checks", "FAILING", { timeout: 15_000 });
    await expect(page.getByTestId("rail-pull-request-state")).toContainText("#1 open");
    await shots(page, "details-rail-pull-request");
    await page.keyboard.press("Escape");
    await accessible(page, "the Pull request pane with a read state", '[data-testid="pane-pull-request"]');
    await shots(page, "pull-request-checks-failing");

    // ---- Checks passing.
    gh.runs = [
      { id: 501, name: "build", status: "completed", conclusion: "success" },
      { id: 503, name: "lint", status: "completed", conclusion: "success" },
    ];
    await page.getByTestId("pane-head-pull-request").getByTestId("pr-pane-refresh").click();
    await expect(state).toHaveAttribute("data-checks", "PASSING", { timeout: 30_000 });
    await expect(pane.getByTestId("pr-pane-state-checks")).toHaveText("Checks: all 2 checks passing");
    const passing = await headerOf(page, sessionId, taskId);
    expect([passing.pullRequest?.state, passing.pullRequest?.checks]).toEqual(["OPEN", "PASSING"]);
    // Every read of the request went to the forge under the Core's token, never from the renderer.
    expect(gh.requests.filter((r) => r.method === "GET" && r.path.startsWith("/repos/o/r/pulls/1")).every((r) => r.authorized)).toBe(true);
    // The row's preview card says it, with when it was read.
    const preview = await previewOf(page, taskId);
    await expect(preview.getByTestId("agent-preview-pr")).toHaveText(/^Pull request #1 · open · all 2 checks passing · read (just now|1m ago)$/);
    await accessible(page, "the preview card with the pull request", '[data-testid="agent-preview"]');
    await shots(page, "preview-card-pull-request");
    await page.keyboard.press("Escape");

    // ---- Restart: the app and its Core stop and start again on the same data. The header is the same.
    await closeApp(app);
    ({ app, page } = await launch(dataDir, { env: { ...env, MODBIT_PR_REFRESH_SECS: "2" } }));
    await setContentSize(app, page, 1440, 900);
    await expect(agentRow(page, taskId).getByTestId("agent-pr")).toHaveAttribute("data-checks", "PASSING", { timeout: 60_000 });
    const after = await headerOf(page, sessionId, taskId);
    expect(after.pullRequest!.readOffset >= passing.pullRequest!.readOffset).toBe(true);
    expect([after.pullRequest?.number, after.pullRequest?.url]).toEqual([1, "https://github.test/o/r/pull/1"]);

    // ---- Archive after merge: off until turned on, in Settings.
    if ((await page.getByTestId("settings-nav").count()) === 0) await page.getByTestId("open-settings").click();
    await expect(page.getByTestId("settings-nav")).toBeVisible();
    await page.getByTestId("settings-nav-tools").click();
    const toggle = page.getByTestId("settings-archive-after-merge");
    await expect(toggle).toBeEnabled({ timeout: 30_000 });
    await expect(toggle).not.toBeChecked();
    expect(await page.evaluate((s) => window.modbit.pullRequestPreferences(s), sessionId)).toEqual({ archiveAfterMerge: false, offset: "0" });
    // The switch shows what the Core answered, so it turns once the Core has recorded the change.
    await toggle.click();
    await expect(toggle).toBeChecked({ timeout: 15_000 });
    await expect.poll(async () => (await page.evaluate((s) => window.modbit.pullRequestPreferences(s), sessionId)).archiveAfterMerge).toBe(true);
    await accessible(page, "the archive after merge setting", '[data-testid="settings-pull-requests"]');
    await shots(page, "settings-archive-after-merge");
    await toNewTask(page);

    // ---- Merged on the server: the Core's schedule reads it, archives the task, and the list offers Undo.
    gh.pull!.state = "closed";
    gh.pull!.merged = true;
    const undo = page.getByTestId("tray").filter({ hasText: "Archived" });
    await expect(undo).toBeVisible({ timeout: 30_000 });
    await expect(undo).toContainText("Its pull request merged and archive after merge is on.");
    await expect(agentRow(page, taskId)).toHaveCount(0);
    // The pane, still docked, shows the Core's read of the merge though the list no longer holds the task.
    await expect(page.getByTestId("pr-pane-state")).toHaveAttribute("data-state", "MERGED", { timeout: 15_000 });
    await expect(page.getByTestId("pr-pane-read-at")).toContainText("by the Core's schedule");
    const merged = await headerOf(page, sessionId, taskId);
    expect([merged.archived, merged.pullRequest?.state, merged.pullRequest?.trigger]).toEqual([true, "MERGED", "SCHEDULE"]);
    await accessible(page, "the archive after merge notice", '[data-testid="tray-host"]');
    await shots(page, "archived-after-merge");
    await undo.getByRole("button", { name: "Undo" }).click();
    await expect(agentRow(page, taskId)).toBeVisible({ timeout: 15_000 });
    await expect(agentRow(page, taskId).getByTestId("agent-pr")).toHaveAttribute("data-state", "MERGED");
    // The undo stands: the schedule does not read a settled request again, and nothing archives it twice.
    const reads = gh.requests.filter((r) => r.method === "GET" && r.path.startsWith("/repos/o/r/pulls/1")).length;
    await page.waitForTimeout(5_000);
    await expect(agentRow(page, taskId)).toBeVisible();
    expect((await headerOf(page, sessionId, taskId)).archived).toBe(false);
    expect(gh.requests.filter((r) => r.method === "GET" && r.path.startsWith("/repos/o/r/pulls/1")).length, "a merged request is not read on a schedule").toBe(reads);
    await shots(page, "restored-after-undo");
  } finally {
    await closeApp(app);
    model.server.close();
    gh.server.close();
  }
});
